async def newpage(b, w=1366, h=900, theme=None, storage=None, block_storage=False):
    ctx = await b.new_context(viewport={'width': w, 'height': h})
    pg = await ctx.new_page()
    pg.errs = []
    pg.on('pageerror', lambda e: pg.errs.append(str(e)))
    await pg.route('**/fonts.googleapis.com/**', lambda r: r.abort())
    init = ''
    if storage:
        init += 'try{' + ''.join(f'localStorage.setItem({json.dumps(k)},{json.dumps(v)});' for k, v in storage.items()) + '}catch(e){}'
    if block_storage:
        init += "Object.defineProperty(window,'localStorage',{get(){throw new Error('denied')}});"
    if theme:
        init += f"document.addEventListener('DOMContentLoaded',()=>document.documentElement.dataset.theme='{theme}');"
    if init: await pg.add_init_script(init)
    await pg.goto(URL); await pg.wait_for_timeout(300)
    return pg

async def go(pg, v):
    await pg.evaluate(f"location.hash='{v}'"); await pg.wait_for_timeout(250)

