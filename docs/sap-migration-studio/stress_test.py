        rec('Accessibility', 'No serious/critical WCAG 2 AA violations', not serious, str(tot)[:300])
        await pg.context.close()

        # 9. Load performance
        pg = await newpage(b)
        t = await pg.evaluate("performance.getEntriesByType('navigation')[0].domContentLoadedEventEnd")
