        rows = ['id,name,street,city,postal_code,country,tax_number,email'] + [f'C{i},Firm {i%7000} Ltd,{i} Main Rd,Cape Town,{8000+i%50},{"ZA" if i%9 else "za"},{4000000000+i%7000},{"x@y.co" if i%5 else "bad@"}' for i in range(20000)]
